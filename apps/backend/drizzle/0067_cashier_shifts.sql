-- Cashier shifts: the stint at the drawer that a closing report reports on.
--
-- Three facts the POS could not state before this table existed: what float the
-- drawer started with, when the stint opened and closed, and whether the money
-- in the drawer at the end matched the money the system expected. The first two
-- were unrecorded; the third was never asked.
--
-- Sales and cash movements are attached by foreign key rather than gathered by
-- a time window, so a shift that closes after midnight still reports as one
-- shift and no clock skew can re-bucket a sale. See db/schema.ts for the rest
-- of the reasoning, including why opening_float is NOT a cashflow row.

CREATE TABLE IF NOT EXISTS "cashier_shifts" (
  "id"            integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "outlet_id"     integer NOT NULL,
  "user_id"       text NOT NULL,
  "cashier_name"  varchar(100) NOT NULL,
  "opening_float" numeric(14, 2) DEFAULT '0' NOT NULL,
  "opened_at"     timestamp with time zone DEFAULT now() NOT NULL,
  "closed_at"     timestamp with time zone,
  "counted_cash"  numeric(14, 2),
  "expected_cash" numeric(14, 2),
  "variance"      numeric(14, 2),
  "closing_note"  varchar(255)
);
