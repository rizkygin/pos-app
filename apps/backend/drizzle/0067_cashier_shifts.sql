-- ── What belongs to a shift ─────────────────────────────────────────────────
-- Both nullable, and both stay nullable. Selling with no shift open is a real
-- state (nobody tapped the button) and money still moves when the counter is
-- closed (the owner settling an invoice from the office). Those rows simply
-- appear on no closing report. Every historical row is one of them, which is
-- why there is no backfill here: inventing a shift for orders that were never
-- rung up under one would fabricate a reconciliation that never happened.

ALTER TABLE "orders" ADD COLUMN IF NOT EXISTS "shift_id" integer;
