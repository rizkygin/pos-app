-- One open shift per outlet. Not a nicety: without it a second "Buka Shift"
-- tap — or a second device at the same counter — splits one drawer's takings
-- across two shifts, and neither of them reconciles against the cash in it.
CREATE UNIQUE INDEX IF NOT EXISTS "cashier_shifts_one_open_per_outlet"
  ON "cashier_shifts" ("outlet_id") WHERE "closed_at" IS NULL;
