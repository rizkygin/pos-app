-- One option = one product the cashier can pick from a group. It is a real
-- products row (is_for_sale = false keeps it out of the POS grid on its own),
-- which is where its stock, recipe, buying_price and avg_cost come from.
--
-- `price` is what the CUSTOMER pays for it, and it lives here rather than on
-- the product because the same telur can be 5.000 on one dish and free on
-- another. 0 is a real, useful value: a free add-on that still consumes stock
-- and still costs money is exactly the case a POS should be able to state.
--
-- deleted_at, and no hard delete once sold: a held tab in a cashier's
-- localStorage may reference this option for days. Resolution reads archived
-- rows too, so removing an option from the menu never blocks payment for a cart
-- that already contains it.
CREATE TABLE IF NOT EXISTS "addon_group_options" (
  "id"         integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "group_id"   integer NOT NULL,
  "product_id" text NOT NULL,
  "price"      numeric(14, 2) DEFAULT '0' NOT NULL,
  "sort_order" integer DEFAULT 0 NOT NULL,
  "updated_at" timestamp with time zone,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "deleted_at" timestamp with time zone
);
