-- ── The catalogue ───────────────────────────────────────────────────────────
-- A group is one question put to the cashier: "Topping?", "Level pedas?".
-- Groups are per OUTLET, not per product, so "Topping" is defined once and
-- attached to twenty dishes (product_addon_groups below). Renaming it is then
-- one row instead of twenty.
--
-- min_select/max_select encode the rules. min_select >= 1 is what "wajib pilih"
-- means — there is no separate required flag to disagree with it. max_select
-- NULL is unlimited.
--
-- THESE RULES GOVERN COMPOSITION, NEVER SETTLEMENT. They are enforced in the
-- picker when the cashier is choosing. Checkout accepts whatever a tab already
-- holds: a tab parked before the owner tightened a rule must still be able to
-- be paid for. A POS sale must never fail at the counter because a settings
-- page changed while a customer stood there (same reason a missing open shift
-- does not block a sale — see cashier_shifts in db/schema.ts).
CREATE TABLE IF NOT EXISTS "addon_groups" (
  "id"         integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "outlet_id"  integer NOT NULL,
  "name"       varchar(60) NOT NULL,
  "min_select" integer DEFAULT 0 NOT NULL,
  "max_select" integer,
  "sort_order" integer DEFAULT 0 NOT NULL,
  "updated_at" timestamp with time zone,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "deleted_at" timestamp with time zone
);
