-- Product add-ons ("Topping", "Level Pedas", "Ukuran").
--
-- An add-on is a CHILD ORDER LINE, not a new kind of thing. It is an ordinary
-- product sold alongside a parent line and pointed at it by parent_detail_id.
-- That one decision is what makes the rest of this free:
--
--   * cost      applySaleStockOut is called with the CHILD's order_detail_id,
--               so the ledger tags the add-on's movements to the add-on's own
--               line. cogs.ts already costs per line and needs no change.
--   * stock     a tracked add-on decrements itself; a composition expands its
--               recipe to leaves. Same code path as any other line.
--   * refunds   applyOrderStockReturn replays by order_id, so children come
--               back with their parent. Nothing to teach it.
--   * revenue   summary_price on each row is what THAT product sold for, so a
--               plain sum over the order's lines is still the order total.
--
-- The alternative — an addons table hanging off the line, or a json blob —
-- would have needed its own stock-out, its own cost freeze, and its own
-- cancellation replay: three duplicates of logic this codebase deliberately
-- keeps in one writer (lib/cost.ts postMovement).
--
-- THE INVARIANT, which every reader below depends on:
--   for every row, summary_price is what the customer paid for THAT product
--   and unit_cost/the ledger is what THAT product cost.
-- Never fold an add-on's price into its parent's summary_price. Both would then
-- carry it, revenue would double count, and COGS — which never reads
-- summary_price — would not, so margin would silently improve.

-- ── The dead column ─────────────────────────────────────────────────────────
-- "extra" was declared in 0000 and never written by anything, in any version:
-- every row is NULL. It was the obvious place to put add-ons and it is the
-- wrong one — a json blob cannot be joined for "how many extra telur did we
-- sell", cannot carry a foreign key for the ledger to tag, and cannot be
-- filtered when counting items. Dropped so it can't be reached for later.
ALTER TABLE "orderDetails" DROP COLUMN IF EXISTS "extra";
