-- ── The parent link ─────────────────────────────────────────────────────────
-- NULL = an ordinary line. Non-NULL = an add-on belonging to that line.
--
-- ON DELETE CASCADE because an add-on cannot outlive the thing it was added to.
-- Only ever one level deep: a child must never itself be a parent (enforced in
-- the write path, not here — a self-referencing depth check in SQL costs more
-- than it protects).
ALTER TABLE "orderDetails" ADD COLUMN IF NOT EXISTS "parent_detail_id" integer;
